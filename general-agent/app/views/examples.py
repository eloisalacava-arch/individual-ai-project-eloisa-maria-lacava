"""Read-only view of the two shipped case studies.

Nothing here writes to ``runs/`` or ``comparison/``. The results were produced by
the command line; this page only reads the tables.
"""

from __future__ import annotations

import streamlit as st

from app import report_support, result_view, workspace
from app.state import go

CASE_STUDIES = [
    {
        "run_id": "imdb_case_study",
        "label": "IMDb sentiment (binary)",
        "note": "200 movie reviews. Primary reference: manual annotations. "
                "Predictions are reused from an earlier run; the case study makes "
                "no new model calls.",
    },
    {
        "run_id": "phrasebank_75agree",
        "label": "Financial PhraseBank (three ordered classes)",
        "note": "300 sentences sampled from the ≥75% annotator-agreement subset. "
                "Licence CC BY-NC-SA 3.0: non-commercial, not redistributed.",
    },
]


def render() -> None:
    st.subheader("Case studies")
    st.caption("The two studies shipped with the engine, read-only. Open the "
               "interface fresh to build your own study.")
    if st.button("Back to a new study"):
        go(1)

    choice = st.selectbox("Study", CASE_STUDIES,
                          format_func=lambda item: item["label"])
    run_id = choice["run_id"]
    directory = workspace.run_dir(run_id)
    st.markdown(f"<span class='ga-muted'>{choice['note']}</span>",
                unsafe_allow_html=True)

    if not (directory / "results").exists():
        st.warning(f"No results found for {run_id}. Run the command line stages; "
                   "this page never writes.")
        return

    frames = result_view.load_results(directory)
    accuracy = result_view.accuracy_row(frames)
    if accuracy:
        columns = st.columns(4)
        columns[0].metric("Rows analysed", f"{int(accuracy.get('n', 0))}")
        columns[1].metric("Accuracy", result_view.fmt(accuracy.get("accuracy")))
        columns[2].metric("Balanced accuracy",
                          result_view.fmt(accuracy.get("balanced_accuracy")))
        kappas = result_view.kappa_rows(frames)
        unweighted = next((row for row in kappas if "unweighted" in row["metric"]), None)
        columns[3].metric("Cohen's kappa",
                          result_view.fmt(unweighted["value"]) if unweighted
                          else "not estimable")

    matrix, _ = result_view.confusion_frames(directory)
    if matrix is not None and not matrix.empty:
        st.markdown("#### Confusion matrix")
        display = matrix.rename_axis("human \\\\ AI", axis=0).rename_axis("AI answer", axis=1)
        try:
            st.dataframe(display.style.background_gradient(cmap="Blues").format("{:d}"),
                         width="stretch")
        except Exception:
            st.dataframe(display, width="stretch")

    per_class = result_view.per_class_rows(frames)
    if per_class is not None:
        columns = [c for c in ["class", "n_reference", "precision", "recall", "f1"]
                   if c in per_class.columns]
        st.markdown("#### By category")
        st.dataframe(per_class[columns], width="stretch", hide_index=True)

    _case_report_block(run_id)

    report = workspace.PROJECT_ROOT / "comparison" / "report.md"
    if report.exists():
        with st.expander("Cross-dataset report (generated by stage 07)"):
            st.markdown(report.read_text(encoding="utf-8"))
    _comparison_block()


def _case_report_block(run_id: str) -> None:
    st.markdown("#### Full report")
    st.caption("A single document for this study, composed from its result files. "
               "No model call; the case-study results are not modified.")
    if not report_support.config_available(run_id):
        st.info("No study configuration was found for this case study.")
        return
    study = report_support.study_report_paths(run_id)
    label = ("Regenerate full report (PDF)" if study["pdf"].exists()
             else "Generate full report (PDF)")
    columns = st.columns(2)
    if columns[0].button(label, key=f"report_build_{run_id}"):
        with st.spinner("Composing the report…"):
            try:
                report_support.build_study(run_id)
            except Exception as exc:
                st.error(f"Could not build the report: {type(exc).__name__}: {exc}")
            else:
                st.rerun()
    if not report_support.pdf_available():
        st.caption("PDF export needs ReportLab: `uv sync --extra pdf`.")
    columns = st.columns(2)
    if study["markdown"].exists():
        columns[0].download_button(
            "Full report (Markdown)", data=study["markdown"].read_bytes(),
            file_name=f"study_report_{run_id}.md", mime="text/markdown")
    if study["pdf"].exists():
        columns[1].download_button(
            "Download Full Report (PDF)", data=study["pdf"].read_bytes(),
            file_name=f"study_report_{run_id}.pdf", mime="application/pdf")


def _comparison_block() -> None:
    st.markdown("#### Cross-dataset comparison report")
    st.caption("The two shipped studies side by side. Preserved from stage 07; a "
               "separate document from the per-study reports.")
    paths = report_support.comparison_paths()
    if not paths["source"].exists():
        st.info("Run stage 07 (`scripts/07_compare.py`) first.")
        return
    label = ("Regenerate comparison report (PDF)" if paths["pdf"].exists()
             else "Generate comparison report (PDF)")
    if st.button(label, key="report_build_comparison"):
        with st.spinner("Composing the comparison report…"):
            try:
                report_support.build_comparison()
            except Exception as exc:
                st.error(f"Could not build the comparison report: "
                         f"{type(exc).__name__}: {exc}")
            else:
                st.rerun()
    if not report_support.pdf_available():
        st.caption("PDF export needs ReportLab: `uv sync --extra pdf`.")
    columns = st.columns(2)
    if paths["markdown"].exists():
        columns[0].download_button(
            "Comparison report (Markdown)", data=paths["markdown"].read_bytes(),
            file_name="cross_dataset_report.md", mime="text/markdown")
    if paths["pdf"].exists():
        columns[1].download_button(
            "Download Full Report (PDF)", data=paths["pdf"].read_bytes(),
            file_name="cross_dataset_report.pdf", mime="application/pdf")
